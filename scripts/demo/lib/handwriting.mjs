// ------------------------------------------------------------------ randomness (seeded)
export function rng(seed = 7) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Resamples a polyline every `step` units. */
function resample(pts, step) {
  const out = [pts[0]];
  let carry = 0;
  for (let i = 1; i < pts.length; i++) {
    const [x0, y0] = pts[i - 1];
    const [x1, y1] = pts[i];
    const l = Math.hypot(x1 - x0, y1 - y0);
    let d = step - carry;
    while (d <= l) {
      out.push([x0 + ((x1 - x0) * d) / l, y0 + ((y1 - y0) * d) / l]);
      d += step;
    }
    carry = l - (d - step);
  }
  const last = pts[pts.length - 1];
  const e = out[out.length - 1];
  if (Math.hypot(last[0] - e[0], last[1] - e[1]) > step * 0.2) out.push(last);
  return out;
}

/** Adds a pressure curve (light at the ends) and a slow wobble. */
function inkify(pts, r, { wobble = 0.6, p0 = 0.32, p1 = 0.68 } = {}) {
  const n = pts.length;
  const ph1 = r() * 6.28;
  const ph2 = r() * 6.28;
  const f = 0.5 + r() * 0.6;
  return pts.map(([x, y], i) => {
    const t = n > 1 ? i / (n - 1) : 0;
    const w = Math.sin(t * Math.PI);
    const p = p0 + (p1 - p0) * Math.pow(w, 0.45) + (r() - 0.5) * 0.04;
    return [x + Math.sin(i * 0.17 * f + ph1) * wobble, y + Math.sin(i * 0.13 * f + ph2) * wobble, Math.round(Math.min(1, Math.max(0.1, p)) * 100) / 100];
  });
}

/**
 * Lays out `text` with its baseline-left at (x, y) and cap height `size` (pixels or canvas
 * units). Returns { strokes: [[[x, y, p], ...], ...], width }.
 */
export function handwrite(text, x, y, size, { seed = 1, slant = 0.16, spacing = 0.08, step } = {}) {
  const r = rng(seed);
  const strokes = [];
  let cx = 0; // em
  const top = y - size; // y of the em box's top
  const chars = [...text];
  for (let i = 0; i < chars.length; i++) {
    let ch = chars[i];
    let scale = 1;
    let dy = 0;
    if ((ch === '^' || ch === '_') && i + 1 < chars.length) {
      const sup = ch === '^';
      ch = chars[++i];
      scale = 0.6;
      dy = sup ? -0.12 : 0.62;
    }
    if (ch === ' ') {
      cx += 0.32;
      continue;
    }
    const g = G[ch];
    if (!g) throw new Error(`no glyph for ${JSON.stringify(ch)}`);
    const jx = (r() - 0.5) * 0.04;
    const jy = (r() - 0.5) * 0.05;
    const js = 1 + (r() - 0.5) * 0.06;
    for (const s of g.s) {
      const pts = s.map(([gx, gy]) => {
        const ex = cx + jx + gx * scale * js;
        const ey = dy + jy + gy * scale * js;
        return [x + (ex + (1 - ey) * slant) * size, top + ey * size];
      });
      strokes.push(inkify(resample(pts, step ?? Math.max(1.5, size * 0.06)), r, { wobble: size * 0.012 }));
    }
    cx += (g.w + spacing) * scale;
  }
  return { strokes, width: cx * size };
}

/** A hand-drawn rectangle in one stroke (corners slightly overshot, a small closing overlap). */
export function roughRect(x, y, w, h, { seed = 3, rough = 1 } = {}) {
  const r = rng(seed);
  const j = () => (r() - 0.5) * Math.min(w, h) * 0.06 * rough;
  const pts = [
    [x + j(), y + j()],
    [x + w + j(), y + j()],
    [x + w + j(), y + h + j()],
    [x + j(), y + h + j()],
    [x + j(), y + j()],
    [x + w * 0.12, y + j() * 0.5],
  ];
  return [inkify(resample(pts, 3), r, { wobble: 1.2 * rough })];
}

/** A hand-drawn arrow: a slightly bowed shaft and a two-stroke head. */
export function roughArrow(x0, y0, x1, y1, { seed = 5, head = 16, bow = 0.06 } = {}) {
  const r = rng(seed);
  const mx = (x0 + x1) / 2;
  const my = (y0 + y1) / 2;
  const nx = -(y1 - y0);
  const ny = x1 - x0;
  const shaft = C([x0, y0], [mx + nx * bow, my + ny * bow], [x1, y1]);
  const a = Math.atan2(y1 - y0, x1 - x0);
  const hd = (da) => [x1 - head * Math.cos(a + da), y1 - head * Math.sin(a + da)];
  return [inkify(resample(shaft, 3), r, { wobble: 0.8 }), inkify(resample([hd(0.45), [x1, y1], hd(-0.45)], 2), r, { wobble: 0.4 })];
}

/** A hand-drawn ellipse (a loop that overshoots its start a little). */
export function roughEllipse(cx, cy, rx, ry, { seed = 9 } = {}) {
  const r = rng(seed);
  const a0 = -100 + r() * 20;
  return [inkify(resample(A(cx, cy, rx, ry, a0, a0 - 380), 3), r, { wobble: 1.5 })];
}

/** A hand-drawn straight line. */
export function roughLine(x0, y0, x1, y1, { seed = 11 } = {}) {
  const r = rng(seed);
  return [inkify(resample([[x0, y0], [(x0 + x1) / 2 + (r() - 0.5) * 3, (y0 + y1) / 2 + (r() - 0.5) * 3], [x1, y1]], 3), r, { wobble: 0.8 })];
}

/** Converts strokes to the canvas model's flat [x, y, p, ...] arrays. */
export const flat = (strokes) => strokes.map((s) => s.flatMap(([x, y, p]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10, p]));
