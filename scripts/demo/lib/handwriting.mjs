/**
 * A small single-stroke "handwriting" font for the demo's pen strokes: lowercase letters,
 * some capitals, digits and maths symbols, written with a slant, a little wobble and a
 * pressure curve, plus hand-drawn shapes (rough rectangles, arrows, ellipses, lines).
 * Glyphs are in em units: x from 0, y from 0 (ascender/cap top) to 1 (baseline); x-height
 * at 0.46, descenders to 1.35. `^x` and `_x` write x as a superscript or subscript.
 */

// ------------------------------------------------------------------ geometry helpers
const rad = (d) => (d * Math.PI) / 180;
/** Arc from a0 to a1 degrees (y down: 90 is the bottom, -90 the top; decreasing = anticlockwise on screen). */
function A(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(6, Math.ceil(Math.abs(a1 - a0) / 9));
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = rad(a0 + ((a1 - a0) * i) / n);
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
}
/** Catmull-Rom curve through the points. */
function C(...p) {
  const out = [];
  const P = [p[0], ...p, p[p.length - 1]];
  for (let i = 1; i < P.length - 2; i++) {
    for (let k = 0; k < 10; k++) {
      const t = k / 10;
      const t2 = t * t;
      const t3 = t2 * t;
      const f = (a, b, c, d) => 0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3);
      out.push([f(P[i - 1][0], P[i][0], P[i + 1][0], P[i + 2][0]), f(P[i - 1][1], P[i][1], P[i + 1][1], P[i + 2][1])]);
    }
  }
  out.push(p[p.length - 1]);
  return out;
}
const cat = (...parts) => parts.flat().filter((p) => Array.isArray(p) && typeof p[0] === 'number');

